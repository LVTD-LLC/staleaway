const assert = require("assert").strict;
const fs = require("fs");
const vm = require("vm");
const { LIMITS, FIELDS, GROUPS, validUrl, parseList, compare, csv } = require("../src/tools/content_inventory_compare");
let checks = 0;
const raw = Object.fromEntries(FIELDS.map(field => [field.key, field.example]));
let result = compare(raw);
assert.equal(result.status, "ready");
assert.equal(result.rows.length, 5);
assert.deepEqual(result.counts, {"111": 1, "110": 1, "101": 0, "100": 1, "011": 1, "010": 0, "001": 1});
assert.equal(result.rows.filter(row => row.key === "111")[0].url, "https://example.com/about");
checks++;
// Every nonempty membership pattern, including equal list counts with different members.
const patterns = ["111", "110", "101", "100", "011", "010", "001"];
const all = Object.fromEntries(FIELDS.map((field, index) => [field.key, patterns.filter(key => key[index] === "1").map(key => `https://example.com/${key}`).join("\n")]));
result = compare(all);
patterns.forEach(key => assert.equal(result.counts[key], 1));
assert.equal(result.rows.length, 7);
checks++;
const urls = ["https://example.com/", "https://example.com", "https://EXAMPLE.com/", "http://example.com/", "https://example.com/A", "https://example.com/a", "https://example.com/%61", "https://example.com/a%2F", "https://example.com/a%2f", "https://xn--bcher-kva.de/", "https://example.com/a,b\"c"];
const parsed = parseList(" \n" + urls.join("\r\n") + "\r\n" + urls[0] + "  \n");
assert.equal(parsed.urls.size, urls.length);
assert.deepEqual([...parsed.urls], urls);
assert.equal(parsed.duplicates, 1);
assert.equal(parsed.blanks, 2);
checks++;
for (const invalid of ["", "https://example.com?", "https://example.com/#", "https://example.com?a=1", "https://user:secret@example.com/a", "https://@example.com/", "https://example.com/a b", "https://example.com/\\foo", "https://example.com/\u0000", "\thttps://example.com/", "https://example.com/a\u2028b", "mailto:user@example.com", "file:///tmp/a", "//example.com/", "https://localhost/a", "https://a.local/a", "https://a.internal/", "http://10.2.3.4/", "http://127.1/", "http://0x7f000001/", "http://192.168.1.2/", "http://172.17.0.1/", "http://169.254.1.1/", "http://100.64.0.1/", "http://[::1]/", "http://[::ffff:127.0.0.1]/", "http://[2001:4860:4860::8888]/", "https://example.com:bad/", "https://example.com/" + "a".repeat(LIMITS.url)]) {
  assert.equal(compare({...raw, inventory: invalid}).status, "invalid", `invalid comparison: ${JSON.stringify(invalid)}`);
}
for (const valid of ["https://example.com/", "HTTP://Example.COM/A", "https://example.com:8443/a", "https://bücher.de/a", "https://example.com./a"]) assert.equal(validUrl(valid), true, valid);
assert.equal(validUrl("https:///example.com/a"), false);
assert.equal(validUrl("https:////example.com/a"), false);
const bad = compare({...raw, inventory: "https://example.com/ok\nprivate-synthetic-marker?token=secret\nhttps://example.com/ok"});
assert.equal(bad.status, "invalid");
assert.match(bad.errors.inventory, /line numbers 2/);
assert.equal(JSON.stringify(bad).includes("private-synthetic-marker"), false);
assert.equal(csv(bad), "");
checks++;
const maxUrl = "https://example.com/" + "a".repeat(LIMITS.url - "https://example.com/".length);
assert.equal(validUrl(maxUrl), true);
assert.equal(validUrl(maxUrl + "a"), false);
const many = Array.from({length: 2000}, (_, i) => `https://example.com/${i}`).join("\n");
result = compare({inventory: many, sitemap: many, imported: many});
assert.equal(result.status, "ready");
assert.equal(result.rows.length, 2000);
assert.equal(result.counts["111"], 2000);
assert.equal(parseList(many + "\nhttps://example.com/x").error.includes("2,000"), true);
assert.equal(parseList("é".repeat(125001)).error.includes("250,000"), true);
assert.equal(parseList(" ".repeat(250001)).error.includes("250,000"), true);
checks++;
const tricky = 'https://example.com/a,b"c';
result = compare({inventory: tricky, sitemap: tricky, imported: tricky});
const output = csv(result);
assert.equal(output.split("\r\n").length, 3);
assert.equal(output.includes('"https://example.com/a,b""c","yes","yes","yes"'), true);
assert.equal(output.includes('"In all three lists"'), true);
assert.equal(csv(compare({inventory: many, sitemap: many, imported: many})).split("\r\n").length, 2002);
checks++;
// Exercise controller lifecycle with inert DOM/network boundaries, not real input uploads.
const source = fs.readFileSync("frontend/src/controllers/content_inventory_compare_controller.js", "utf8");
assert.equal(/innerHTML|fetch\(|localStorage|sessionStorage|XMLHttpRequest|location\.|clipboard/.test(source), false);
const context = {Controller: class {}, FIELDS, GROUPS, LIMITS, compare, csv};
vm.createContext(context);
vm.runInContext(source.replace(/^import .*;\n/gm, "").replace("export default class", "globalThis.Tool = class"), context);
const tool = new context.Tool();
function element() {return {hidden: false, disabled: false, textContent: "stale", replaceChildren() {this.textContent = "";}, removeAttribute() {}, focus() {}};}
for (const key of ["result", "download", "rows", "counts", "listStats", "displayed", "summary", "status"]) tool[key + "Target"] = element();
tool.inputTargets = FIELDS.map(field => ({...element(), value: field.example, dataset: {field: field.key}}));
tool.errorTargets = FIELDS.map(field => ({...element(), dataset: {field: field.key}}));
tool.result = compare(raw);
tool.invalidate();
assert.equal(tool.result, null);
assert.equal(tool.resultTarget.hidden, true);
assert.equal(tool.downloadTarget.disabled, true);
assert.equal(tool.rowsTarget.textContent, "");
assert.equal(tool.errorTargets.every(error => error.textContent === ""), true);
tool.clear();
assert.equal(tool.inputTargets.every(input => input.value === ""), true);
assert.equal(tool.result, null);
tool.example();
assert.deepEqual(tool.inputTargets.map(input => input.value), FIELDS.map(field => field.example));
assert.equal(tool.result, null);
assert.equal(tool.downloadTarget.disabled, true);
checks++;
console.log(`Inventory comparison: ${checks} contract groups passed.`);
